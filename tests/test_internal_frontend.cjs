'use strict';
const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
let source=fs.readFileSync('static/app.js','utf8');
source=source.substring(0,source.lastIndexOf('(async function init(){'));
const ctx={document:{querySelector:()=>({}),addEventListener:()=>{}},window:{addEventListener:()=>{}},console,setTimeout,clearTimeout};
ctx.AREA_TARGETS={};
vm.createContext(ctx);vm.runInContext(source,ctx);vm.runInContext(fs.readFileSync('static/internal.js','utf8'),ctx);
const html=vm.runInContext(`opsLaunchTable([{id:'launch-1',name:'Dossier <script>secret</script>',order_ref:'FR-42',article:'Modèle <img src=x>',client_name:'Client & contact',quantity:1500,provisional_ref:null,definitive_ref:null,responsible:null,status:'En cours',alerts:2,last_activity:'2026-10-21T10:00:00+00:00',completion:{state:'incomplete',percent:50,present_due:1,due_count:2,partial_visibility:false}}])`,ctx);
assert(html.includes('&lt;img src=x&gt;')&&!html.includes('<img src=x>'));
assert(html.includes('Client &amp; contact'));
assert(html.includes('data-ops-target='));
assert(html.includes('aria-valuenow="50"'));
assert(html.includes('data-label="Commande / article"'));
const notDue=vm.runInContext(`opsCompletion({state:'not_due',percent:null,present_due:0,due_count:0})`,ctx);
assert(notDue.includes('Non exigible')&&!notDue.includes('role="meter"'));
const partial=vm.runInContext(`opsCompletion({state:'partial',percent:100,present_due:1,due_count:1,partial_visibility:true})`,ctx);
assert(partial.includes('Vue partielle')&&!partial.includes('Complet</span>'));
const escaped=vm.runInContext(`opsAction({launch_id:'launch-1',title:'<svg onload=alert(1)>',launch_name:'Lot',description:'Commentaire <b>interne</b>',priority:'high'})`,ctx);
assert(!escaped.includes('<svg onload=')&&escaped.includes('&lt;svg onload='));
const css=fs.readFileSync('static/internal.css','utf8');
assert(css.includes('@media(max-width:820px)')&&css.includes('.drawer-open .sidebar'));
assert(css.includes('.ops-table.responsive thead{display:none}'));
assert(css.includes('prefers-reduced-motion'));
// Le portail Client (static/client/) n'utilise que l'API client.
const client=fs.readFileSync('static/client/api.js','utf8')+fs.readFileSync('static/client/client.js','utf8');
assert(client.includes("const BASE = '/api/client'"));
assert(!client.includes('/api/workspace/')&&!client.includes('/api/admin/'));
console.log('Pilotage interne : rendu, états, navigation précise, responsive et échappement HTML OK');
